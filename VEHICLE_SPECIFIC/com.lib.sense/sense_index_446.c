void sense_index_446 (Can_Msg *can_msg )
{        
    UInt8 i;

	if ( can_msg->data._8_[0] != 0x00 ) 
	{
		for ( i = 0; i < 8; i++ )
		{ 
			if ( (can_msg->data._8_[0] == 0x0C) || (can_msg->data._8_[0] == 0x04) ) 
			{ 
				GLOBAL_LOCK_446[i] = can_msg->data._8_[i];
				GLOBAL_UNLOCK_446[i] = can_msg->data._8_[i];
			}
		}
	}
}
	
