Boolean detect_ign_search( void )
{	  
	can_usr_rx_reg_fast( CAN_DEV_0 , (Reg_Func)ignition_search_can0) ;
	TRACE("\rDETECT_IGN_SEARCH - before start waiting for event");
	                     
	return os_evt_wait( detect_evt , DETECT_IGN_OK , DETECT_IGN_OK , DETECT_SEARCH_TIMEOUT ) ;       
    //return detect_sense_ign_flag;
	//return TRUE;
}

void ignition_search_can0( Can_Msg *can_msg )
{
	TRACE("\rIGNITION_SEARCH_CAN0 here");
	if (can_msg->id == 0x3B3 )
	{
		//if ( ((DATA1(0) & 0xF0) == 0x40) || (DATA1(0) & 0xF0) == 0x80) 
		if ((((can_msg->data._8_[0]&0xF0) == 0x40) || (can_msg->data._8_[0]&0xF0) == 0x80))
		{
			os_evt_signal( detect_evt , DETECT_IGN_OK ) ;
			car.bits.car = DETECT_CAR_TYPE1; 
		}
	}
}


