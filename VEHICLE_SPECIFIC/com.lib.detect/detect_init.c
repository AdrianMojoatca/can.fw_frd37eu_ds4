void detect_frd_sense_ign (Can_Msg *can_msg)
{
	TRACE("\r\nDETECTION HERE\r\n" );
	if ( ((DATA1(0) & 0xF0) == 0x40) || (DATA1(0) & 0xF0) == 0x80) 
	{
		TRACE("\r\nDETECTION => IGNITION ON\r\n" );
		detect_sense_ign_flag = TRUE;
		car.bits.can0_detected = TRUE;
		car.bits.car = DETECT_CAR_TYPE1;

		os_evt_signal( detect_evt , DETECT_IGN_OK ) ; 
	}
	else 
	{
		detect_sense_ign_flag = FALSE;
		car.bits.can0_detected = FALSE;
	}
}

void detect_init( void )
{
	TRACE("\r\nDETECT INIT: register CAN0 slow hook (id=0x3B3)\r\n");
	can_usr_rx_reg_slow( CAN_DEV_0 , (Reg_Func)detect_frd_sense_ign , 0x3B3 ) ;                      
	TRACE("\r\nDETECT INIT: CAN0 slow hook ready\r\n");
}


